// Regenerates editor/data.js from ../lib and ../examples.
// Run:  node editor/tools/build-data.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const fix = (s) => s.replace(/require\(\s*"\.\.\/lib\/(\w+)"\s*\)/g, 'require("$1")');

const lib = {};
for (const f of fs.readdirSync(path.join(root, 'lib'))) if (f.endsWith('.exb')) lib[f] = read('lib/' + f);

const meta = {
  'hello.exb':     'مرحباً — جولة سريعة',
  'calc.exb':      'آلة حاسبة (Lexer + Pratt)',
  'json.exb':      'مفسّر JSON',
  'tinylang.exb':  'لغة صغيرة تُترجم إلى bytecode',
};
const examples = [];
for (const [f, title] of Object.entries(meta)) examples.push({ name: f, title, code: fix(read('examples/' + f)) });

const out = '// Generated by tools/build-data.mjs — do not edit.\n' +
  'self.EXB_DATA = ' + JSON.stringify({ lib, examples }) + ';\n';
fs.writeFileSync(path.join(root, 'editor', 'data.js'), out);
console.log('data.js:', out.length, 'bytes');
