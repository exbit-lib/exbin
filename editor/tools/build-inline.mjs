// Generates editor/inline.js: worker source + data + wasm (base64) so the editor also runs when
// index.html is opened directly from disk (file://), where browsers block Worker/fetch of local files.
// Run:  node editor/tools/build-inline.mjs     (re-run after changing worker.js, data.js or exbin.wasm)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = (f) => fs.readFileSync(path.join(dir, f));
const wasm = rd('exbin.wasm').toString('base64');
const worker = 'self.EXB_WASM_B64=' + JSON.stringify(wasm) + ';\n' + rd('data.js').toString('utf8') + '\n' + rd('worker.js').toString('utf8');
fs.writeFileSync(path.join(dir, 'inline.js'), '// Generated by tools/build-inline.mjs — do not edit.\nself.EXB_INLINE = ' + JSON.stringify({ worker }) + ';\n');
console.log('inline.js:', fs.statSync(path.join(dir, 'inline.js')).size, 'bytes');
